static C1: OnceLock<Vec<u8>> = OnceLock::new();
static C2: OnceLock<Vec<u8>> = OnceLock::new();
static LOGIN_C31: OnceLock<Vec<u8>> = OnceLock::new();
static LOGIN_C32: OnceLock<Vec<u8>> = OnceLock::new();

#[tokio::main]
async fn main() {
    env_logger::init();
    log::info!("starting...");
    C1.set(read_hex("BIN_C1")).expect("failed to set C1");
    C2.set(read_hex("BIN_C2")).expect("failed to set C2");
    LOGIN_C31
        .set(read_hex("BIN_LOGIN_C31"))
        .expect("failed to set C31");
    LOGIN_C32
        .set(read_hex("BIN_LOGIN_C32"))
        .expect("failed to set C32");
    let service = Router::new()
        .route("/healthz", get(healthz))
        .route("/readyz", get(readyz))
        .route("/generate", get(generate));
    let addr = TcpListener::bind("0.0.0.0:8080")
        .await
        .expect("failed to bind 0.0.0.0:8080");
    log::info!("listening in 0.0.0.0:8080...");
    axum::serve(addr, service)
        .await
        .unwrap_or_else(|e| panic!("{e:?}"));
}

fn read_hex(var: &str) -> Vec<u8> {
    hex::decode(env::var(var).unwrap_or_else(|_| panic!("var: {var} not declared")))
        .unwrap_or_else(|_| panic!("failed to decode {var}"))
}

#[derive(Debug, Deserialize)]
struct GenerateQuery {
    timestamp: String,
    path: String,
    kind: String,
}

#[derive(Debug, Serialize)]
#[serde(untagged)]
enum GenerateResult {
    Success { success: bool, value: String },
    Failed { success: bool, message: String },
}

async fn generate(Query(query): Query<GenerateQuery>) -> impl IntoResponse {
    log::info!("Generated from: {query:?}");
    let (c31, c32): (&[u8], &[u8]) = match query.kind.as_str() {
        "login" => (
            LOGIN_C31
                .get()
                .expect("C31 is not initialized, this should not happen"),
            LOGIN_C32
                .get()
                .expect("C32 is not initialized, this should not happen"),
        ),
        _ => {
            return (
                StatusCode::BAD_REQUEST,
                Json(GenerateResult::Failed {
                    success: false,
                    message: format!("no kind named \"{}\"", query.kind),
                }),
            );
        }
    };
    let Ok(timestamp) = query.timestamp.parse::<u64>() else {
        return (
            StatusCode::BAD_REQUEST,
            Json(GenerateResult::Failed {
                success: false,
                message: "timestamp is not a valid number".into(),
            }),
        );
    };
    let result = match chilo::generate(
        &BIN,
        C1.get()
            .expect("C1 is not initialized, this should not happen"),
        C2.get()
            .expect("C2 is not initialized, this should not happen"),
        c31,
        c32,
        timestamp,
        query.path.as_bytes(),
    ) {
        Ok(result) => result,
        Err(e) => {
            return (
                StatusCode::INTERNAL_SERVER_ERROR,
                Json(GenerateResult::Failed {
                    success: false,
                    message: format!("failed to generate value: {e}"),
                }),
            );
        }
    };
    let base64 = base64::prelude::BASE64_STANDARD.encode(result);
    (
        StatusCode::OK,
        Json(GenerateResult::Success {
            success: true,
            value: base64,
        }),
    )
}

const fn check_ready() -> Option<String> {
    None
}

async fn readyz() -> impl IntoResponse {
    check_ready().map_or_else(
        || (StatusCode::OK, Json(json!({"status":"ready"}))),
        |e| {
            (
                StatusCode::SERVICE_UNAVAILABLE,
                Json(json!({"status": "not ready", "reason": e})),
            )
        },
    )
}

async fn healthz() -> impl IntoResponse {
    (StatusCode::OK, Json(json!({"health":"ok"})))
}
